// Category mapping cleaner
function cleanCategory(cat, pkg) {
  if (pkg === 'party') {
    if (cat.includes('Kändis') || cat.includes('Kultur')) return 'Personer & Kultur';
    if (cat.includes('Mat')) return 'Mat & Dryck';
    return 'Fest & Nöje';
  }
  if (pkg === 'klurigt') {
    if (cat.includes('Filosofi') || cat.includes('Psykologi') || cat.includes('Koncept') || cat.includes('Abstrakt')) return 'Klurigt & Abstrakt';
    return 'Vetenskap & Teknik';
  }
  if (pkg === 'familj') {
    if (cat.includes('Djur') || cat.includes('Natur')) return 'Djur & Natur';
    if (cat.includes('Mat')) return 'Mat & Dryck';
    if (cat.includes('Lek') || cat.includes('Vardag')) return 'Familj & Vardag';
    return 'Familj & Vardag';
  }
  // standard
  if (cat.includes('Föremål')) return 'Föremål';
  if (cat.includes('Djur') || cat.includes('Natur')) return 'Djur & Natur';
  if (cat.includes('Mat') || cat.includes('Dryck')) return 'Mat & Dryck';
  if (cat.includes('Yrken') || cat.includes('Roller')) return 'Yrken & Roller';
  if (cat.includes('Platser')) return 'Platser & Resor';
  if (cat.includes('Verb')) return 'Verb & Handlingar';
  if (cat.includes('Kultur') || cat.includes('Kändis')) return 'Personer & Kultur';
  return 'Klurigt & Abstrakt';
}

